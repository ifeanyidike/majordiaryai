async def test_marking_read_is_the_recipients_alone(api, db, farm, make_user):
    """Read state is a column here rather than a join table because there is
    exactly one reader — so nobody else can clear their badge."""
    tech = await make_user(UserRole.technician)
    intruder = await make_user(UserRole.technician)
    admin = await make_user(UserRole.admin)

    async with api("admin", user_id=admin.id) as admin_client:
        message_id = (await _office_alert(
            admin_client, body="Read me", recipient_id=str(tech.id))).json()["id"]

    async with api("technician", user_id=intruder.id) as client:
        assert (await client.patch(f"/messages/{message_id}/read")).status_code == 404

    async with api("technician", user_id=tech.id) as client:
        first = await client.patch(f"/messages/{message_id}/read")
        second = await client.patch(f"/messages/{message_id}/read")

    assert first.status_code == 200
    assert first.json()["read_at"] is not None
    # Idempotent: two devices, or a double tap, must not move the timestamp.
    assert second.json()["read_at"] == first.json()["read_at"]


