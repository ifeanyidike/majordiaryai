# ── route changes ────────────────────────────────────────────────────

async def test_a_route_change_reaches_both_technicians(api, db, farm, make_user):
    """The one who most needs to know is the one being taken OFF the farm —
    and by the time the change is saved they can no longer see that farm's
    notifications at all. A farm-addressed alert would reach everyone except
    the person whose day just changed.
    """
    from sqlalchemy import select

    outgoing = await make_user(UserRole.technician, "Outgoing")
    incoming = await make_user(UserRole.technician, "Incoming")
    admin = await make_user(UserRole.admin)
    farm.assigned_technician_id = outgoing.id
    await db.flush()

    async with api("admin", user_id=admin.id) as client:
        r = await client.patch(
            f"/farms/{farm.id}", json={"assigned_technician_id": str(incoming.id)},
        )
    assert r.status_code == 200, r.text

    messages = (await db.execute(
        select(Message).where(
            Message.channel == MessageChannel.office_alert,
            Message.farm_id == farm.id,
        )
    )).scalars().all()
    by_recipient = {m.recipient_id: m.body for m in messages}

    assert set(by_recipient) == {outgoing.id, incoming.id}
    assert "no longer on your route" in by_recipient[outgoing.id]
    assert "added to your route" in by_recipient[incoming.id]


async def test_a_farm_edit_that_leaves_the_route_alone_says_nothing(
    api, db, farm, make_user,
):
    """Renaming a farm is not a route change. Announcing one every time
    anything is saved is how a feed becomes noise."""
    from sqlalchemy import select

    tech = await make_user(UserRole.technician)
    admin = await make_user(UserRole.admin)
    farm.assigned_technician_id = tech.id
    await db.flush()

    async with api("admin", user_id=admin.id) as client:
        r = await client.patch(f"/farms/{farm.id}", json={"name": "Renamed Farm"})
    assert r.status_code == 200, r.text

    messages = (await db.execute(
        select(Message).where(Message.farm_id == farm.id)
    )).scalars().all()
    assert messages == []


async def test_reassigning_a_single_day_names_the_day(api, db, farm, make_user):
    from datetime import timedelta

    from sqlalchemy import select

    from app.core.timeutils import local_today

    standing = await make_user(UserRole.technician, "Standing")
    relief = await make_user(UserRole.technician, "Relief")
    admin = await make_user(UserRole.admin)
    farm.assigned_technician_id = standing.id
    await db.flush()
    when = local_today() + timedelta(days=2)

    async with api("admin", user_id=admin.id) as client:
        r = await client.put(
            f"/farms/{farm.id}/visit-assignments",
            json={"visit_date": when.isoformat(),
                  "assigned_technician_id": str(relief.id)},
        )
    assert r.status_code == 200, r.text

    bodies = [
        m.body for m in (await db.execute(
            select(Message).where(Message.farm_id == farm.id)
        )).scalars().all()
    ]
    assert any(when.isoformat() in b and "added to your route" in b for b in bodies)
    assert any(when.isoformat() in b and "no longer on your route" in b for b in bodies)
