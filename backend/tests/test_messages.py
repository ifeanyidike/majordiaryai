"""Alarms and Office Alerts — the two person-to-person feeds.

A notification is generated by the system, addressed to a FARM, and read by
whoever has access to that farm. These are the opposite, and the whole value
of keeping them separate is that the sender is known without reading the
message: an alarm is the barn calling, an office alert is the office calling.
So the tests that matter are the ones about who may write where, and whether
the message reaches a person rather than a farm.
"""

import uuid

import pytest

from app.models.models import Message, MessageChannel, UserRole


async def _alarm(client, **body):
    return await client.post("/messages/", json={"channel": "alarm", **body})


async def _office_alert(client, **body):
    return await client.post("/messages/", json={"channel": "office_alert", **body})


# ── who may write to which feed ──────────────────────────────────────

async def test_a_farm_owner_can_raise_an_alarm_to_their_technician(
    api, db, farm, make_user,
):
    tech = await make_user(UserRole.technician, "Route Tech")
    farm.assigned_technician_id = tech.id
    await db.flush()

    async with api("farm", farm_id=farm.id) as client:
        r = await _alarm(client, body="Cow in pen 4 is down, come today.")

    assert r.status_code == 201, r.text
    sent = r.json()
    # No recipient was named: an owner writing from their own farm is answered
    # by that farm's standing technician, which is the only person they know.
    assert sent["recipient_id"] == str(tech.id)
    assert sent["farm_id"] == str(farm.id)
    assert sent["channel"] == "alarm"


async def test_an_owner_cannot_post_to_the_office_alerts_feed(api, db, farm, make_user):
    """If an owner could post here, the feed would stop meaning "the office
    said so" — which is the only reason it exists apart from Alarms."""
    tech = await make_user(UserRole.technician)

    async with api("farm", farm_id=farm.id) as client:
        r = await _office_alert(client, body="Your route changed.", recipient_id=str(tech.id))

    assert r.status_code == 403
    assert "admin" in r.json()["detail"]


async def test_a_technician_cannot_post_to_either_feed(api, db, farm, make_user):
    """Both feeds are addressed TO technicians. A technician writing into them
    would be talking to themselves, and on the office feed would be putting
    words in the administrator's mouth."""
    other = await make_user(UserRole.technician)

    async with api("technician") as client:
        alarm = await _alarm(client, body="hello", recipient_id=str(other.id),
                             farm_id=str(farm.id))
        office = await _office_alert(client, body="hello", recipient_id=str(other.id))

    assert alarm.status_code == 403
    assert office.status_code == 403


async def test_an_administrator_can_raise_an_office_alert(api, db, make_user):
    tech = await make_user(UserRole.technician)
    admin = await make_user(UserRole.admin, "The Office")

    async with api("admin", user_id=admin.id) as client:
        r = await _office_alert(client, body="Start at Cedar Lane on Friday.",
                                recipient_id=str(tech.id))

    assert r.status_code == 201, r.text
    assert r.json()["sender_name"] == "The Office"
    assert r.json()["sender_role"] == "admin"


# ── addressing ───────────────────────────────────────────────────────

async def test_an_alarm_needs_somebody_to_answer_it(api, db, farm):
    """A farm with no technician assigned has nobody to raise an alarm to.
    Silently dropping it would be the worst outcome: the owner believes help
    is coming."""
    farm.assigned_technician_id = None
    await db.flush()

    async with api("farm", farm_id=farm.id) as client:
        r = await _alarm(client, body="Cow down.")

    assert r.status_code == 409
    assert "no technician" in r.json()["detail"].lower()


async def test_a_message_cannot_be_addressed_to_a_farm_owner(api, db, farm, make_user):
    """These feeds run one way. A message addressed to an owner would sit in a
    feed their app never opens."""
    owner = await make_user(UserRole.farm, "Owner")
    admin = await make_user(UserRole.admin)

    async with api("admin", user_id=admin.id) as client:
        r = await _office_alert(client, body="hello", recipient_id=str(owner.id))

    assert r.status_code == 422
    assert "technician" in r.json()["detail"]


async def test_an_unlinked_farm_account_cannot_raise_an_alarm(api, db, make_user):
    """A farm account with no farm has no barn to report from, and farm_id is
    taken from the account rather than the request precisely so it cannot
    claim someone else's."""
    async with api("farm", farm_id=None) as client:
        r = await _alarm(client, body="Cow down.")

    assert r.status_code == 409
    assert "not linked to a farm" in r.json()["detail"].lower()


async def test_an_owner_cannot_raise_an_alarm_about_another_farm(
    api, db, farm, make_user,
):
    """farm_id comes from the account, not the body — so naming a farm they do
    not own changes nothing rather than being honoured."""
    tech = await make_user(UserRole.technician)
    farm.assigned_technician_id = tech.id
    from app.models.models import Farm
    other = Farm(id=uuid.uuid4(), name="Somebody Else's", owner_name="X", herd_size=0)
    db.add(other)
    await db.flush()

    async with api("farm", farm_id=farm.id) as client:
        r = await _alarm(client, body="Cow down.", farm_id=str(other.id))

    assert r.status_code == 201, r.text
    assert r.json()["farm_id"] == str(farm.id)


# ── the feed itself ──────────────────────────────────────────────────

async def test_each_feed_returns_only_its_own_channel(api, db, farm, make_user):
    """Two feeds in one table: a leak between them would put the barn's
    emergency in the middle of the office's scheduling notes."""
    tech = await make_user(UserRole.technician)
    admin = await make_user(UserRole.admin)
    farm.assigned_technician_id = tech.id
    await db.flush()

    async with api("farm", farm_id=farm.id) as owner_client:
        await _alarm(owner_client, body="Cow down.")
    async with api("admin", user_id=admin.id) as admin_client:
        await _office_alert(admin_client, body="Route change.", recipient_id=str(tech.id))

    async with api("technician", user_id=tech.id) as tech_client:
        alarms = (await tech_client.get("/messages/?channel=alarm")).json()
        office = (await tech_client.get("/messages/?channel=office_alert")).json()

    assert [m["body"] for m in alarms] == ["Cow down."]
    assert [m["body"] for m in office] == ["Route change."]


