"""The two person-to-person feeds: Alarms and Office Alerts.

A Notification is generated by the system, addressed to a FARM, and several
people read it. These are the other direction: one person writes to one
technician, and nothing generates them but a person deciding to.

  Alarms        farm owner    -> technician   ("the cow in pen 4 is down")
  Office Alerts administrator -> technician   ("your route changed for Friday")

Why not a third `type` on notifications: read state there lives in a join
table because a farm notification has many readers, the delivery side effect
is an email to the FARM, and farm access governs who can see it. A message has
exactly one reader, no email, and is addressed to a person -- including a
person who may have just lost access to the farm it mentions, which is
precisely the case a farm-addressed notification cannot reach.
"""

import uuid
from typing import List, Optional, Sequence, Union

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.timeutils import local_today
from app.models.models import (
    Farm, FarmVisitAssignment, Message, MessageChannel, User, UserRole,
)
from app.services import push


async def send(
    db: AsyncSession,
    channel: MessageChannel,
    sender_id: uuid.UUID,
    recipient_id: uuid.UUID,
    body: str,
    farm_id: Optional[uuid.UUID] = None,
    cow_id: Optional[uuid.UUID] = None,
) -> Message:
    """Queue one message, and a push to the recipient's phones. The caller
    commits; the push goes out only if that commit happens."""
    message = Message(
        id=uuid.uuid4(),
        channel=channel,
        sender_id=sender_id,
        recipient_id=recipient_id,
        farm_id=farm_id,
        cow_id=cow_id,
        body=body.strip(),
    )
    db.add(message)

    farm = await db.get(Farm, farm_id) if farm_id else None
    if channel is MessageChannel.alarm:
        title = f"Alarm · {farm.name}" if farm else "Alarm"
    else:
        title = f"Office Alert · {farm.name}" if farm else "Office Alert"
    push.queue_push(
        db, recipient_id, title, message.body,
        # What the app needs to open the right feed when the alert is tapped.
        {"channel": channel.value, "message_id": str(message.id)},
        channel.value,
    )
    return message


async def send_office_alert(
    db: AsyncSession,
    sender_id: uuid.UUID,
    recipient_id: Optional[uuid.UUID],
    body: str,
    farm_id: Optional[uuid.UUID] = None,
) -> Optional[Message]:
    """An administrator's message to one technician. No recipient, no message."""
    if recipient_id is None:
        return None
    return await send(
        db, MessageChannel.office_alert, sender_id, recipient_id, body, farm_id=farm_id,
    )


def farm_names(farms: Sequence[Farm]) -> str:
    """"A", "A and B", "A, B and C"."""
    names = [f.name for f in farms]
    return names[0] if len(names) == 1 else f"{', '.join(names[:-1])} and {names[-1]}"


async def announce_route_change(
    db: AsyncSession,
    admin_id: uuid.UUID,
    farms: Union[Farm, Sequence[Farm]],
    previous_technician_id: Optional[uuid.UUID],
    new_technician_id: Optional[uuid.UUID],
    when: Optional[str] = None,
) -> int:
    """Tell both technicians when farms move between them.

    Both, and by message rather than by notification, because the one who most
    needs to know is the one being taken OFF the farm -- and by the time the
    change is saved they can no longer see that farm's notifications at all.
    A farm-addressed alert would reach everyone except the person whose day
    just changed.

    One message each however many farms move (Routes, test results Nov 10:
    "two notifications are sent"). A single farm is linked, so the message
    opens it.
    """
    if previous_technician_id == new_technician_id:
        return 0
    farms = [farms] if isinstance(farms, Farm) else list(farms)
    if not farms:
        return 0

    names = farm_names(farms)
    one = len(farms) == 1
    farm_id = farms[0].id if one else None
    day = f" on {when}" if when else ""
    sent = 0
    if previous_technician_id is not None:
        await send_office_alert(
            db, admin_id, previous_technician_id,
            f"{names} {'is' if one else 'are'} no longer on your route{day}.", farm_id=farm_id,
        )
        sent += 1
    if new_technician_id is not None:
        await send_office_alert(
            db, admin_id, new_technician_id,
            f"{names} {'has' if one else 'have'} been added to your route{day}.", farm_id=farm_id,
        )
        sent += 1
    return sent


async def alarm_recipients(
    db: AsyncSession, farm_id: uuid.UUID, sender_id: uuid.UUID,
) -> List[uuid.UUID]:
    """Who an alarm goes to when the sender names nobody.

    The technician covering the farm TODAY, when a day has been handed to
    someone; otherwise the farm's own technician. A farm with no technician
    reaches the office (every active admin but the sender) rather than being
    refused, since the owner has no one to name. Empty only when there is
    nobody at all.
    """
    covering = await db.scalar(
        select(FarmVisitAssignment.assigned_technician_id).where(
            FarmVisitAssignment.farm_id == farm_id,
            FarmVisitAssignment.visit_date == local_today(),
        )
    )
    if covering is not None:
        return [covering]
    farm = await db.get(Farm, farm_id)
    if farm is not None and farm.assigned_technician_id is not None:
        return [farm.assigned_technician_id]
    return list((await db.execute(
        select(User.id).where(
            User.role == UserRole.admin, User.is_active.is_(True), User.id != sender_id,
        ).order_by(User.name)
    )).scalars())


async def is_technician(db: AsyncSession, user_id: uuid.UUID) -> bool:
    """Both feeds are addressed to technicians; admins may also be on the
    receiving end, since they cover routes too."""
    role = await db.scalar(select(User.role).where(User.id == user_id))
    return role in (UserRole.technician, UserRole.admin)
